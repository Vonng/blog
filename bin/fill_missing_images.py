#!/usr/bin/env python3
"""Fill missing image/assets from sibling repositories.

Input: tmp/missing-images.tsv (generated by previous checker)
Search roots:
  /Users/vonng/www/vonng.com
  /Users/vonng/www/vonng.com-new
  /Users/vonng/www/vonng2
  /Users/vonng/www/site.cc

Usage:
  python3 bin/fill_missing_images.py --dry-run
  python3 bin/fill_missing_images.py --apply
"""

from __future__ import annotations

import argparse
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple


STOP_TOKENS = {
    "content",
    "blog",
    "post",
    "posts",
    "article",
    "articles",
    "img",
    "image",
    "images",
    "assets",
    "static",
    "public",
    "cn",
    "zh",
    "en",
    "index",
    "md",
    "docs",
}

ROOT_PRI = {
    "/Users/vonng/www/vonng.com": 40,
    "/Users/vonng/www/vonng.com-new": 35,
    "/Users/vonng/www/vonng2": 30,
    "/Users/vonng/www/site.cc": 25,
}


@dataclass(frozen=True)
class MissingEntry:
    file: Path
    line: int
    typ: str
    path: str
    raw: str


@dataclass(frozen=True)
class MatchResult:
    entry: MissingEntry
    source: Path
    dest: Path
    score: int
    second_score: int
    candidates: int


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Fill missing images/assets from sibling repos")
    p.add_argument("--missing-tsv", default="tmp/missing-images.tsv")
    p.add_argument("--apply", action="store_true", help="copy files and patch malformed local absolute paths")
    p.add_argument("--dry-run", action="store_true", help="only report")
    p.add_argument("--min-score", type=int, default=35)
    p.add_argument("--min-gap", type=int, default=4)
    return p.parse_args()


def tokenize(value: str) -> List[str]:
    out: List[str] = []
    for part in Path(value).parts:
        for token in re.split(r"[^a-zA-Z0-9]+", part.lower()):
            if token and token not in STOP_TOKENS:
                out.append(token)
    return out


def read_missing(repo: Path, missing_tsv: Path) -> List[MissingEntry]:
    if not missing_tsv.exists():
        raise FileNotFoundError(f"missing tsv not found: {missing_tsv}")
    lines = missing_tsv.read_text(encoding="utf-8", errors="ignore").splitlines()
    entries: List[MissingEntry] = []
    seen = set()
    for line in lines[1:]:
        if not line.strip():
            continue
        file_s, line_s, typ, path, raw = line.split("\t", 4)
        key = (file_s, path)
        if key in seen:
            continue
        seen.add(key)
        entries.append(
            MissingEntry(
                file=repo / file_s,
                line=int(line_s),
                typ=typ,
                path=path,
                raw=raw,
            )
        )
    return entries


def index_candidates(roots: Sequence[Path]) -> Dict[str, List[Path]]:
    idx: Dict[str, List[Path]] = {}
    for root in roots:
        if not root.exists():
            continue
        for p in root.rglob("*"):
            if not p.is_file():
                continue
            idx.setdefault(p.name.lower(), []).append(p)
    return idx


def root_priority(path: Path, roots: Sequence[Path]) -> int:
    path_s = str(path)
    for root in roots:
        root_s = str(root)
        if path_s.startswith(root_s):
            return ROOT_PRI.get(root_s, 0)
    return 0


def source_penalty(path: Path) -> int:
    p = str(path).lower()
    # Prefer source-like files over generated public artifacts.
    if "/content/" in p or "/static/" in p:
        return 4
    if "/public/" in p:
        return -4
    return 0


def score_candidate(entry: MissingEntry, cand: Path, roots: Sequence[Path]) -> int:
    score = 0
    score += root_priority(cand, roots)
    score += source_penalty(cand)

    src_ctx = set(tokenize(str(entry.file.parent)))
    ref_ctx = set(tokenize(str(Path(entry.path).parent)))
    want = src_ctx | ref_ctx

    c_low = str(cand).lower()
    c_toks = set(tokenize(c_low))
    overlap = want & c_toks
    score += 7 * len(overlap)

    src_name = entry.file.parent.name.lower()
    if src_name and src_name in c_low:
        score += 10

    ref_parent = Path(entry.path).parent.name.lower()
    if ref_parent and ref_parent not in {".", ".."} and ref_parent in c_low:
        score += 8

    for part in entry.file.parent.parts:
        p = part.lower()
        if p in STOP_TOKENS:
            continue
        if f"/{p}/" in c_low:
            score += 2

    ref_parent_norm = str(Path(entry.path).parent).replace("\\", "/").strip("/").lower()
    if ref_parent_norm and ref_parent_norm != ".":
        tail = "/" + ref_parent_norm + "/"
        if tail in c_low:
            score += 12

    return score


def resolve_destination(repo: Path, entry: MissingEntry) -> Tuple[Path, bool]:
    path = entry.path
    # Malformed local absolute paths accidentally embedded in markdown.
    if path.startswith("/Users/") or path.startswith("Users/"):
        return entry.file.parent / Path(path).name, True

    if path.startswith("/"):
        return repo / "static" / path.lstrip("/"), False

    return (entry.file.parent / path).resolve(), False


def select_matches(
    repo: Path,
    entries: Sequence[MissingEntry],
    idx: Dict[str, List[Path]],
    roots: Sequence[Path],
    min_score: int,
    min_gap: int,
) -> Tuple[List[MatchResult], List[Tuple[MissingEntry, str]], List[Tuple[MissingEntry, str]]]:
    mapped: List[MatchResult] = []
    ambiguous: List[Tuple[MissingEntry, str]] = []
    unresolved: List[Tuple[MissingEntry, str]] = []

    for entry in entries:
        name = Path(entry.path).name.lower()
        cands = idx.get(name, [])
        if not cands:
            unresolved.append((entry, "no-candidate"))
            continue

        scored = [(score_candidate(entry, cand, roots), cand) for cand in cands]
        scored.sort(key=lambda x: (-x[0], str(x[1])))

        best_score, best = scored[0]
        second_score = scored[1][0] if len(scored) > 1 else -999

        if best_score < min_score:
            unresolved.append((entry, f"low-score:{best_score}"))
            continue

        # accept ties at high confidence only
        if len(scored) > 1 and (best_score - second_score) < min_gap and best_score < 80:
            ambiguous.append((entry, f"best={best_score},second={second_score}"))
            continue

        dest, _needs_patch = resolve_destination(repo, entry)
        mapped.append(
            MatchResult(
                entry=entry,
                source=best,
                dest=dest,
                score=best_score,
                second_score=second_score,
                candidates=len(cands),
            )
        )

    return mapped, ambiguous, unresolved


def patch_malformed_path(entry: MissingEntry) -> bool:
    path = entry.path
    if not (path.startswith("/Users/") or path.startswith("Users/")):
        return False

    file = entry.file
    text = file.read_text(encoding="utf-8", errors="ignore")
    replacement = Path(path).name
    if path not in text:
        return False
    file.write_text(text.replace(path, replacement), encoding="utf-8")
    return True


def main() -> int:
    args = parse_args()
    repo = Path.cwd()
    missing_tsv = (repo / args.missing_tsv).resolve()

    roots = [
        Path("/Users/vonng/www/vonng.com"),
        Path("/Users/vonng/www/vonng.com-new"),
        Path("/Users/vonng/www/vonng2"),
        Path("/Users/vonng/www/site.cc"),
    ]

    entries = read_missing(repo, missing_tsv)
    idx = index_candidates(roots)
    mapped, ambiguous, unresolved = select_matches(repo, entries, idx, roots, args.min_score, args.min_gap)

    print(f"entries={len(entries)}")
    print(f"mapped={len(mapped)}")
    print(f"ambiguous={len(ambiguous)}")
    print(f"unresolved={len(unresolved)}")

    if not (args.apply and not args.dry_run):
        print("\nSample mapped:")
        for m in mapped[:40]:
            rel_dest = m.dest.relative_to(repo) if str(m.dest).startswith(str(repo)) else m.dest
            print(f"{m.entry.file.relative_to(repo)}:{m.entry.line} :: {m.entry.path} -> {m.source} => {rel_dest} (s={m.score})")

        print("\nSample unresolved:")
        for entry, why in unresolved[:40]:
            print(f"{entry.file.relative_to(repo)}:{entry.line} :: {entry.path} ({why})")
        print("\nSample ambiguous:")
        for entry, why in ambiguous[:40]:
            print(f"{entry.file.relative_to(repo)}:{entry.line} :: {entry.path} ({why})")
        return 0

    copied = 0
    skipped_existing = 0
    patched = 0

    for m in mapped:
        dest = m.dest
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists():
            skipped_existing += 1
        else:
            shutil.copy2(m.source, dest)
            copied += 1

        if patch_malformed_path(m.entry):
            patched += 1

    # write mapping report
    report = repo / "tmp" / "missing-images-mapping.tsv"
    report.parent.mkdir(parents=True, exist_ok=True)
    with report.open("w", encoding="utf-8") as f:
        f.write("file\tline\tref_path\tsource\tdestination\tscore\n")
        for m in mapped:
            f.write(
                "\t".join(
                    [
                        str(m.entry.file.relative_to(repo)),
                        str(m.entry.line),
                        m.entry.path,
                        str(m.source),
                        str(m.dest),
                        str(m.score),
                    ]
                )
                + "\n"
            )

    unresolved_report = repo / "tmp" / "missing-images-unresolved.tsv"
    with unresolved_report.open("w", encoding="utf-8") as f:
        f.write("file\tline\tref_path\treason\n")
        for entry, why in unresolved:
            f.write(f"{entry.file.relative_to(repo)}\t{entry.line}\t{entry.path}\t{why}\n")

    ambiguous_report = repo / "tmp" / "missing-images-ambiguous.tsv"
    with ambiguous_report.open("w", encoding="utf-8") as f:
        f.write("file\tline\tref_path\treason\n")
        for entry, why in ambiguous:
            f.write(f"{entry.file.relative_to(repo)}\t{entry.line}\t{entry.path}\t{why}\n")

    print(f"copied={copied}")
    print(f"skipped_existing={skipped_existing}")
    print(f"patched_malformed_paths={patched}")
    print(f"mapping_report={report}")
    print(f"unresolved_report={unresolved_report}")
    print(f"ambiguous_report={ambiguous_report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
